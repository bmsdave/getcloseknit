"""Generate the API contract from the app: contracts/openapi.yaml (app.openapi(), api/area_api/contract) and the
web's types from it, web/src/lib/api-types.gen.ts (web/scripts/gen-api-types.mjs: openapi-typescript, pinned).

    python deploy/tools/gen_openapi.py           rewrite both files (the API venv: fastapi, pyyaml)
    python deploy/tools/gen_openapi.py --check   exit 1 when a committed file is stale (gate.sh)

Neither file is edited by hand: change the models or contract/operations.py, then run this.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
CONTRACT = ROOT / "contracts" / "openapi.yaml"
WEB = ROOT / "web"
TYPES = WEB / "src" / "lib" / "api-types.gen.ts"
HEADER = "# Generated by deploy/tools/gen_openapi.py from the API (api/area_api/contract). Do not edit.\n"


def openapi_yaml() -> str:
    sys.path.insert(0, str(ROOT / "api"))  # this checkout's API, not an installed copy
    from area_api.app import app

    return HEADER + yaml.safe_dump(app.openapi(), sort_keys=False, allow_unicode=True, width=120, default_flow_style=None)


def typescript(contract: Path) -> str:
    with tempfile.TemporaryDirectory() as scratch:
        out = Path(scratch) / "api-types.gen.ts"
        subprocess.run(["node", "scripts/gen-api-types.mjs", str(contract), str(out)], cwd=WEB, check=True)
        return out.read_text()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when the committed files are stale")
    args = parser.parse_args()
    document = openapi_yaml()
    with tempfile.TemporaryDirectory() as scratch:
        contract = Path(scratch) / "openapi.yaml"
        contract.write_text(document)
        types = typescript(contract)
    stale = [path for path, text in ((CONTRACT, document), (TYPES, types))
             if not path.exists() or path.read_text() != text]
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run deploy/tools/gen_openapi.py)", file=sys.stderr)
        return 1 if stale else 0
    CONTRACT.write_text(document)
    TYPES.write_text(types)
    print(f"wrote {CONTRACT.relative_to(ROOT)} and {TYPES.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
