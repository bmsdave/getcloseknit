// The web's API types, generated from contracts/openapi.yaml by openapi-typescript (pinned in package.json).
// Run through deploy/tools/gen_openapi.py, which writes both files; never edit src/lib/api-types.gen.ts by hand.
//   node scripts/gen-api-types.mjs <openapi.yaml> <out.ts>
// Ids the API documents by pattern become the template literal types the web already uses (lib/contracts.ts).
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString, stringToAST } from "openapi-typescript";

const [source, out] = process.argv.slice(2);
if (!source || !out) {
  console.error("usage: node scripts/gen-api-types.mjs <openapi.yaml> <out.ts>");
  process.exit(2);
}

const typeOf = (text) => stringToAST(`type T = ${text};`)[0].type;
const PATTERNS = new Map([
  ["^uk:(lsoa|msoa|lad):E[0-9]{8}$", typeOf('`uk:${"lsoa" | "msoa" | "lad"}:${string}`')],
  ["^uk:lsoa:E[0-9]{8}$", typeOf("`uk:lsoa:${string}`")],
  ["^uk:addr:[0-9a-f]{12}$", typeOf("`uk:addr:${string}`")],
  ["^uk:school:[0-9]{6}$", typeOf("`uk:school:${string}`")],
  // The API's metric ids are its catalogue's rows; the web's METRIC_IDS lists the ones it draws.
  ["^[a-z0-9]+(-[a-z0-9]+)*$", typeOf('import("./contracts").MetricId')],
]);

const ast = await openapiTS(pathToFileURL(source), {
  transform(schema) {
    return schema.type === "string" && schema.pattern ? PATTERNS.get(schema.pattern) : undefined;
  },
});
const header = "// Generated by deploy/tools/gen_openapi.py from contracts/openapi.yaml (openapi-typescript). Do not edit.\n";
writeFileSync(out, header + astToString(ast));
